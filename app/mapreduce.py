"""Режим 3: исчерпывающий обход РЕАЛЬНОГО текста всех файлов (map-reduce).

Крайний случай для агрегационных вопросов, когда быстрого summary-каталога
недостаточно (см. rag._answer_from_catalog). Идея простая и надёжная: пройтись
по всем проиндексированным файлам батчами, на каждом батче спросить модель
«есть здесь релевантное — выпиши», а в конце одним запросом свести все частичные
находки в единый ответ. Гарантированно не пропустит файл, но это N дополнительных
LLM-вызовов — ответ занимает минуты, а не секунды. Включается тумблером в
настройках (search_mode = full_scan) и, в отличие от каталога, работает синхронно
внутри rag.answer_question — вызывающий код должен быть готов к долгому ответу
(вебхуки Пачки/Omnidesk отвечают 200 сразу и шлют результат отдельным сообщением,
поэтому это безопасно для них; для админ-панели «Тест агента» это просто долгий
спиннер).
"""
from __future__ import annotations

import logging
import os

import db
import ingest
import llm

log = logging.getLogger("mapreduce")

_MAP_SYSTEM = (
    "Ты ищешь в документе факты, относящиеся к вопросу пользователя. Прочитай текст и выпиши "
    "ТОЛЬКО то, что прямо относится к вопросу — короткими пунктами. Бери исключительно то, что "
    "реально написано в тексте, ничего не добавляй от себя. У документа в шапке указано, "
    "приоритетный он источник (официальная документация) или вспомогательный (например, "
    "переписка поддержки) — помечай каждый свой пункт той же меткой, чтобы это было видно на "
    "следующем шаге. Если в этом документе нет ничего релевантного вопросу — ответь ровно "
    "одним словом: НЕТ."
)

_REDUCE_SYSTEM = (
    "Тебе даны выдержки, найденные в разных документах базы знаний — каждая помечена именем "
    "файла-источника и тем, приоритетный это источник (официальная документация) или "
    "вспомогательный (например, переписка поддержки). Собери из них ПОЛНЫЙ ответ на вопрос "
    "пользователя. Если вопрос про список (например, список интеграций/систем/касс) — перечисли "
    "ВСЕ уникальные пункты, которые встретились хотя бы в одной выдержке, без пропусков и "
    "повторов. Приоритетным источникам доверяй больше: если приоритетный и вспомогательный "
    "источники расходятся — бери версию приоритетного; вспомогательные используй, чтобы "
    "дополнить пункты, которых нет в приоритетных. Ничего не выдумывай сверх того, что есть "
    "в выдержках.\n\n"
    "ВАЖНО про оформление: НЕ вставляй пометки источника (имена файлов, скобки, ★ и т.п.) "
    "нигде в ответе — пользователь их не увидит, они не нужны. Пиши чистым текстом/списком.\n\n"
    "Ответ уходит в мессенджер (Пачка/Omnidesk) — поддерживается ТОЛЬКО упрощённый Markdown: "
    "**жирный**, _курсив_, `код`, ссылки [текст](url), маркированные/нумерованные списки. "
    "Заголовки через # и ## НЕ поддерживаются (покажутся решётками как есть) — вместо заголовка "
    "раздела используй **жирную строку**. Можно 1-2 уместных смайлика на весь ответ, не больше."
)

# Для внешнего канала (Omnidesk) — среди выдержек попадаются сырые переписки поддержки
# С ДРУГИМИ клиентами. Без этого хинта reduce-шаг может пересказать их данные постороннему.
_EXTERNAL_PRIVACY_HINT = (
    "\n\nВАЖНО: ты отвечаешь ВНЕШНЕМУ КЛИЕНТУ, а не сотруднику компании. Среди выдержек "
    "могут быть переписки поддержки с ДРУГИМИ клиентами (имена, телефоны, email, номера "
    "заказов/карт, детали чужих обращений). НИКОГДА не воспроизводи чужие персональные "
    "данные, даже частично — используй только суть, относящуюся к вопросу, обезличенно. "
    "Не упоминай внутренние процессы и названия внутренних систем/файлов."
)

_BATCH_FILES = 8            # файлов на один map-запрос — компромисс контекст/скорость
_MAX_CHARS_PER_FILE = 6000  # обрезаем очень длинные файлы, чтобы батч не взорвал контекст


def _file_text(rec: dict) -> str:
    path = rec.get("stored_path")
    if not path or not os.path.exists(path):
        return ""
    try:
        return ingest.extract_text(path)[:_MAX_CHARS_PER_FILE]
    except Exception:
        log.exception("full-scan: не удалось прочитать файл %s", rec.get("filename"))
        return ""


def answer(question: str, channel: str = "internal") -> dict:
    files = [f for f in db.list_files() if f["status"] == "ready"]
    prio_ids = db.priority_file_ids()
    # Приоритетные файлы — первыми батчами, чтобы их находки попали в начало
    # reduce-контекста (порядок тоже слегка влияет на то, чему модель отдаёт вес).
    files.sort(key=lambda f: 0 if f["id"] in prio_ids else 1)
    findings: list[str] = []
    scanned = 0

    for i in range(0, len(files), _BATCH_FILES):
        batch = files[i:i + _BATCH_FILES]
        parts = []
        for rec in batch:
            text = _file_text(rec)
            if text.strip():
                tag = "★ приоритетный источник" if rec["id"] in prio_ids else "вспомогательный источник"
                parts.append(f"=== Файл: {rec['filename']} [{tag}] ===\n{text}")
        scanned += len(batch)
        if not parts:
            continue
        user = f"Вопрос: {question}\n\n" + "\n\n".join(parts)
        try:
            out = llm.complete(_MAP_SYSTEM, user, max_tokens=700)
        except llm.LLMNotConfigured:
            raise
        except Exception:
            log.exception("full-scan: ошибка на батче файлов %s",
                          [r["filename"] for r in batch])
            out = ""
        if out and out.strip().upper() != "НЕТ":
            findings.append(out.strip())
        log.info("full-scan: обработано файлов %s/%s, найдено фрагментов %s",
                 scanned, len(files), len(findings))

    if not findings:
        return {
            "answer": "Проверил все файлы базы знаний (" + str(len(files)) + ") — "
                      "информации по этому вопросу не нашлось.",
            "sources": [], "hits": [], "mode": "full_scan",
        }

    reduce_system = _REDUCE_SYSTEM + (_EXTERNAL_PRIVACY_HINT if channel == "external" else "")
    reduce_user = (f"Вопрос: {question}\n\nНайденные выдержки по файлам:\n\n"
                   + "\n\n---\n\n".join(findings))
    answer_text = llm.complete(reduce_system, reduce_user, max_tokens=4000).strip()
    return {"answer": answer_text, "sources": [], "hits": [], "mode": "full_scan"}
