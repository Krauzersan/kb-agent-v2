"""Роутер режимов обработки вопроса: FAST / AGGREGATION / DEEP.

Три принципиально разных сценария, для которых один и тот же top-k поиск не подходит
одинаково хорошо:

- FAST — обычный точечный вопрос («как настроить Х», «почему не работает Y»). Обычный
  гибридный поиск (см. rag._search_with_priority) справляется отлично — это подавляющее
  большинство вопросов.
- AGGREGATION — ответ размазан по многим файлам («перечисли все X», «какие есть Y») —
  см. rag._answer_from_catalog / mapreduce.py.
- DEEP — сложный многосоставной вопрос или запрос на ТЗ/план/инструкцию, который реально
  выигрывает от декомпозиции на подвопросы и структурированной генерации по разделам —
  см. deep.py.

Регекс (_AGG_RE) — быстрый и бесплатный, но ловит только явные ключевые слова: реальные
вопросы формулируются как угодно, и разница между «точечным» и «сложным многосоставным»
вопросом вообще не сводится к ключевым словам. Поэтому регекс здесь — только быстрый
предфильтр для самых очевидных агрегационных случаев (экономит отдельный LLM-вызов на
классификацию), а основной механизм — короткий классифицирующий вызов модели: он смотрит
на СМЫСЛ вопроса, а не на конкретные слова в нём.
"""
from __future__ import annotations

import logging
import re

import llm
import settings_store

log = logging.getLogger("router")

# ---------- регекс-предфильтр агрегационных вопросов (быстрый путь) ----------
#
# Голые \bвсе\b|\bвсех\b|\bвсём\b|\bвсей\b сюда специально не включаем — самые частые
# слова в русском («спасибо всем», «у всех клиентов», «расскажи обо всём»), они ложно
# уводили обычные вопросы в агрегационный режим. «какие ... есть/бывают/существуют/
# поддерживаются» — с любым текстом между словами (обычный порядок «какие X есть»,
# а не только «какие есть X»), плюс «все + существительное» ограничено конкретным
# списком слов-маркеров перечисления (а не голым «все»).
_AGG_RE = re.compile(
    r"перечисли|перечислите|весь список|полный список|список всех|список всей|"
    r"какие\b(?:(?!\?).){0,40}\b(есть|бывают|существуют|поддерживаются)\b|"
    r"\bвсе\s+(способ\w*|вариант\w*|возможност\w*|метод\w*|вид\w*|тип\w*|функци\w*|"
    r"настройк\w*|интеграци\w*|канал\w*|статус\w*|услови\w*|правил\w*|шаг\w*|"
    r"пункт\w*|раздел\w*|инструмент\w*|отчет\w*|отчёт\w*|показател\w*)|"
    r"со всеми|полностью список",
    re.IGNORECASE,
)


def is_aggregation_question(question: str) -> bool:
    return bool(_AGG_RE.search(question or ""))


# ---------- семантическая классификация (LLM) ----------

_ROUTER_SYSTEM = (
    "Классифицируй вопрос пользователя РОВНО в одну из трёх категорий и ответь ОДНИМ "
    "словом, без пояснений и знаков препинания.\n\n"
    "FAST — обычный точечный вопрос с конкретным ответом (как сделать X, что такое Y, "
    "где найти Z, почему не работает N, да/нет-вопрос). Подавляющее большинство вопросов "
    "относится сюда — если сомневаешься, выбирай FAST.\n\n"
    "AGGREGATION — ответ на вопрос представляет собой ПОЛНЫЙ список/перечисление "
    "вариантов, способов, систем и т.п., по своей природе разбросанных по МНОГИМ разным "
    "файлам базы («какие есть способы оплаты», «перечисли все интеграции», «какие кассы "
    "поддерживаются») — то есть по 1-2 источникам такой вопрос закрыть нельзя, нужен обзор "
    "по всей базе.\n\n"
    "DEEP — сложный технический вопрос ИЛИ явный запрос на составление ТЗ/плана/подробной "
    "инструкции, который объединяет НЕСКОЛЬКО разных подтем и нуждается в структурированном "
    "многосоставном ответе (например «составь ТЗ на интеграцию с X», «сравни варианты Y и Z "
    "и предложи архитектуру», «опиши полный процесс от А до Я со всеми нюансами и "
    "исключениями»). Не путай с AGGREGATION: DEEP — про глубину и структуру ОДНОГО сложного "
    "ответа на одну многосоставную задачу, AGGREGATION — про перечисление МНОГИХ похожих "
    "пунктов из разных источников.\n\n"
    "Ответь только одним словом: FAST, AGGREGATION или DEEP."
)

_VALID_MODES = {"fast", "aggregation", "deep"}
_MANUAL_FORCED = {"fast", "deep"}


def classify(question: str) -> str:
    """Возвращает "fast" | "aggregation" | "deep".

    router_mode в настройках — ручной оверрайд: "fast"/"deep" форсируют режим для ЛЮБОГО
    вопроса без обращения к классификатору (быстро и предсказуемо, полностью отключает
    роутер); "auto" (по умолчанию) — обычный путь ниже. Любая ошибка классификации —
    откатываемся на FAST, это самый дешёвый и безопасный режим по умолчанию.
    """
    manual = (settings_store.get("router_mode") or "auto").strip().lower()
    if manual in _MANUAL_FORCED:
        return manual

    question = (question or "").strip()
    if not question:
        return "fast"

    if is_aggregation_question(question):
        return "aggregation"

    try:
        raw = llm.complete(_ROUTER_SYSTEM, question, max_tokens=10)
    except Exception:
        log.exception("Роутер: классификация упала — считаем FAST")
        return "fast"

    word = (raw or "").strip().upper().split()[:1]
    mode = word[0].strip(".,:!?").lower() if word else ""
    if mode not in _VALID_MODES:
        log.warning("Роутер: неожиданный ответ классификатора %r — считаем FAST", raw)
        return "fast"
    return mode
