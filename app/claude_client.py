    "\n\nВАЖНО про источники сейчас: это не дословный текст файлов, а краткое summary каждого "
    "файла (сжатый пересказ, сделан отдельно при индексации). Хорошо подходит для полноты "
    "списка, но для точных цифр, версий и формулировок менее надёжно, чем прямая цитата. Если "
