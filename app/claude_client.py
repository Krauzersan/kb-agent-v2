def _system_prompt(channel: str = "internal", mode: str = "normal") -> str:
    # Роль и правила задаются в панели; правила качества, картинки, бренд, приоритет,
    # форматирование, канал и режим источников — фиксированные.
    role = (settings_store.get("agent_role") or "").strip()
    rules = (settings_store.get("rag_rules") or "").strip()
    channel_hint = _CHANNEL_HINTS.get(channel, _CHANNEL_HINTS["internal"])
    mode_hint = _CATALOG_MODE_HINT if mode == "catalog" else ""
    return (role + ("\n\n" + rules if rules else "")
            + _GUIDELINES + _IMG_HINT + _BRAND_HINT + _PRIORITY_HINT + _FORMAT_HINT
            + channel_hint + mode_hint).strip()


def build_user_message(question: str, hits, channel: str = "internal") -> str:
    label = "Вопрос клиента" if channel == "external" else "Вопрос сотрудника"
    return (
        "Выдержки из базы знаний компании (используй как источник фактов; названия файлов "
        "в ответе не упоминай):\n\n"
        f"{build_context(hits)}\n\n"
        "———\n"
        f"{label}:\n{question}"
    )


class ClaudeNotConfigured(Exception):
    pass


# Клиент пересоздаём, если изменился ключ или прокси.
_client: anthropic.Anthropic | None = None
_client_key: str | None = None
_client_proxy: str | None = None


def _get_client() -> anthropic.Anthropic:
    global _client, _client_key, _client_proxy
    api_key = (settings_store.get("anthropic_api_key") or "").strip()
    if not api_key:
        raise ClaudeNotConfigured(
            "Ключ Claude не задан. Откройте «Настройки» в админ-панели и введите ANTHROPIC_API_KEY."
        )
    # Прокси в поддерживаемой стране — обход региональной блокировки Anthropic (403).
    proxy = (settings_store.get("claude_proxy") or "").strip()
    if _client is None or _client_key != api_key or _client_proxy != proxy:
        if proxy:
            # read=120с: запас на генерацию; через потоковый режим данные идут
            # непрерывно, так что туннель прокси не «засыпает».
            http_client = httpx.Client(
                proxy=proxy,
                timeout=httpx.Timeout(connect=30.0, read=120.0, write=30.0, pool=30.0),
            )
            _client = anthropic.Anthropic(api_key=api_key, http_client=http_client,
                                          max_retries=2)
        else:
            _client = anthropic.Anthropic(api_key=api_key)
        _client_key = api_key
        _client_proxy = proxy
    return _client


def build_context(hits: List[dict]) -> str:
    if not hits:
        return "(в базе знаний ничего не найдено по этому вопросу)"
    blocks = []
    for i, h in enumerate(hits, 1):
        tag = " — ★ приоритетный источник" if h.get("priority") else ""
        blocks.append(f"[{i}] Файл: {h['filename']}{tag}\n{h['text']}")
    return "\n\n".join(blocks)


def _normalize_history(history):
    """Приводим историю к чередованию user/assistant, начиная с user (требование Claude)."""
    msgs = []
    for h in (history or []):
        role = h.get("role")
        content = (h.get("content") or "").strip()
        if role not in ("user", "assistant") or not content:
            continue
        # убираем ведущие assistant и подряд идущие одинаковые роли
        if not msgs and role == "assistant":
            continue
        if msgs and msgs[-1]["role"] == role:
            msgs[-1]["content"] += "\n" + content
        else:
            msgs.append({"role": role, "content": content})
    return msgs


def ask(question: str, hits: List[dict], history=None, channel: str = "internal",
        mode: str = "normal") -> str:
    client = _get_client()
    model = settings_store.get("claude_model")
    max_tokens = int(settings_store.get("claude_max_tokens"))
    effort = (settings_store.get("claude_effort") or "high").strip()
    user_content = build_user_message(question, hits, channel=channel)
    messages = _normalize_history(history)
    if messages and messages[-1]["role"] == "user":
        # последняя реплика уже user — присоединяем к ней контекст+вопрос
        messages[-1]["content"] += "\n\n" + user_content
    else:
        messages.append({"role": "user", "content": user_content})

    # Потоковый режим: токены идут непрерывно — прокси не рвёт соединение.
    system = [{"type": "text", "text": _system_prompt(channel, mode),
               "cache_control": {"type": "ephemeral"}}]

    # Изредка (обрыв соединения через прокси на середине стрима и т.п.) API отвечает
    # 200 OK, но текстовых кусков в стриме не приходит вообще — без исключения, без
    # признаков ошибки. Раньше в этом случае молча уходил невнятный фолбэк. Теперь —
    # один повтор запроса (обычно транзиентная сетевая проблема, повтор помогает),
    # и подробный лог с stop_reason/usage, если пусто и со второго раза.
    for attempt in range(2):
        parts: List[str] = []
        final = None
        with client.messages.stream(
            model=model,
            max_tokens=max_tokens,
            system=system,
            messages=messages,
            output_config={"effort": effort},
        ) as stream:
            for chunk in stream.text_stream:
                parts.append(chunk)
            try:
                final = stream.get_final_message()
            except Exception:
                final = None
        # Модели с усиленными классификаторами безопасности (Opus 5, Fable 5) иногда
        # отклоняют запрос по стоп-причине "refusal" вместо пустого ответа — повтор
        # тут не поможет (это не сетевой сбой), поэтому не тратим вторую попытку.
        if final is not None and getattr(final, "stop_reason", None) == "refusal":
            log.warning("Claude отклонил запрос (refusal): %s",
                        getattr(getattr(final, "stop_details", None), "category", None))
            return ("Не могу ответить на этот вопрос — сработала проверка безопасности "
                    "модели. Попробуйте переформулировать вопрос.")
        answer = "".join(parts).strip()
        if answer:
            return answer
        log.warning(
            "Claude вернул пустой ответ (попытка %s/2): stop_reason=%s, usage=%s",
            attempt + 1, getattr(final, "stop_reason", None), getattr(final, "usage", None),
        )
    return "Не удалось сформировать ответ, попробуйте задать вопрос ещё раз."


def complete(system: str, user: str, max_tokens: int = 400) -> str:
    """Простой служебный вызов модели БЕЗ роли/правил агента (для summary, map-reduce и т.п.).

    Всегда effort=low вместо настройки из панели — это массовые короткие служебные
    вызовы (summary при индексации, map-reduce), а не диалог с пользователем; высокий
    effort тут только замедлил бы индексацию без пользы.
    """
    client = _get_client()
    model = settings_store.get("claude_model")
    resp = client.messages.create(
        model=model,
        max_tokens=max_tokens,
        system=system,
        messages=[{"role": "user", "content": user}],
        output_config={"effort": "low"},
    )
    parts = [b.text for b in resp.content if getattr(b, "type", "") == "text"]
    return "".join(parts).strip()
